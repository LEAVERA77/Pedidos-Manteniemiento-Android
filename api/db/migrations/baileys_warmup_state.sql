-- Borrador: no ejecutar aún en producción. Los contadores representan intentos
-- reservados, no confirmaciones de entrega; se conservan tras errores inciertos.
CREATE TABLE IF NOT EXISTS baileys_warmup_state (
  tenant_id INTEGER PRIMARY KEY REFERENCES clientes(id) ON DELETE RESTRICT,
  warmup_enabled BOOLEAN NOT NULL DEFAULT FALSE,
  warmup_paused BOOLEAN NOT NULL DEFAULT FALSE,
  warmup_started_at TIMESTAMPTZ,
  warmup_forced_ready BOOLEAN NOT NULL DEFAULT FALSE,
  warmup_count_date DATE,
  warmup_daily_sent INTEGER NOT NULL DEFAULT 0 CHECK (warmup_daily_sent >= 0),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK (NOT warmup_enabled OR warmup_started_at IS NOT NULL)
);
REVOKE ALL ON TABLE baileys_warmup_state FROM PUBLIC;
DO $$ BEGIN
 IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='authenticated') THEN
  REVOKE ALL ON TABLE baileys_warmup_state FROM authenticated;
 END IF;
END $$;
-- Auditoría administrativa, transaccional con el cambio; sin cuerpo ni teléfonos.
CREATE TABLE IF NOT EXISTS baileys_admin_audit (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id INTEGER NOT NULL REFERENCES clientes(id) ON DELETE RESTRICT,
 usuario_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE RESTRICT,
 action TEXT NOT NULL CHECK(action IN ('activate','pause','resume','force_ready')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
REVOKE ALL ON TABLE baileys_admin_audit FROM PUBLIC;
DO $$ BEGIN
 IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='authenticated') THEN
  REVOKE ALL ON TABLE baileys_admin_audit FROM authenticated;
 END IF;
END $$;
