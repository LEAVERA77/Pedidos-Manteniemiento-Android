-- Borrador; auditoría de solicitudes de inicio/parada, no incluye QR ni llaves.
CREATE TABLE IF NOT EXISTS baileys_session_admin_audit (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id INTEGER NOT NULL REFERENCES clientes(id) ON DELETE RESTRICT,
 usuario_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE RESTRICT,
 action TEXT NOT NULL CHECK(action IN ('start_request','stop_request')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()
);
REVOKE ALL ON baileys_session_admin_audit FROM PUBLIC;
DO $$ BEGIN
 IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='authenticated') THEN
  REVOKE ALL ON baileys_session_admin_audit FROM authenticated;
 END IF;
END $$;
